import assert from 'node:assert/strict'
import {createEpisode} from '../src/episode.js'
import {createWanted} from '../src/wanted.js'
const saves=new Map()
const storage={getItem:key=>saves.get(key),setItem:(key,value)=>saves.set(key,value)}
let e=createEpisode({storage})
const answer=(resident,choice)=>assert.ok(e.interact({resident,choice})?.ok)
answer('도현','accept')
e=createEpisode({storage})
answer('윤서','deliver')
assert.equal(e.snapshot().money,8500)
assert.equal(e.interact({resident:'윤서',choice:'deliver'}),null)
answer('강 반장','ask-channel')
answer('미라','channel-3')
answer('미라','channel-7')
for(const sight of ['02','03'])assert.ok(e.interact({sight}).ok)
for(const id of ['medkit','coffee','permit'])assert.ok(e.buy(id).ok)
assert.equal(e.use('medkit',{hp:100,maxHealth:100}).ok,false)
assert.equal(e.use('medkit',{hp:80,maxHealth:100}).effect.heal,20)
assert.equal(e.use('coffee').effect.sprintSeconds,30)
const drive=(dt,x=0,z=0)=>e.update(dt,{x,z,driving:true})
drive(0);drive(66)
assert.equal(e.snapshot().status,'failed')
e.retry();drive(0);assert.ok(e.use('permit').ok)
e.fail('체포');e.retry();drive(0);drive(2,2.6,-87);drive(2,2.8,19.5)
assert.equal(createEpisode({storage}).snapshot().completed.length,4)
const w=createWanted(),p={x:0,z:0}
assert.equal(w.tick(50,p,true,true),undefined)
w.report(p,1);assert.equal(w.tick(2,p,true,true),'warning')
w.report(p,1);w.report(p,2);assert.equal(w.level,3)
w.tick(2,{x:3,z:5},false,false);assert.deepEqual(w.lastKnown,p)
assert.equal(w.phase,'search');assert.equal(w.tick(18,p,false,false),'escaped')
w.report(p,2);assert.equal(w.tick(2,p,true,true),'arrest')
console.log('Four missions, reload, failure/retry, rewards, inventory and pursuit outcomes passed.')
